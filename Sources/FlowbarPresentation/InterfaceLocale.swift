import Foundation

/// Локаль интерфейса.
///
/// Все строки проекта написаны по-русски, значит и даты обязаны быть русскими.
/// Системная локаль здесь не годится: у пользователя с английским языком системы
/// под русским текстом появлялось бы «2 seconds ago».
///
/// Единственное место, где локаль задаётся. Когда появится настоящая локализация,
/// меняется только оно.
public enum InterfaceLocale {

  /// Локаль, которой форматируются даты и числа интерфейса.
  public static let current = Locale(identifier: "ru_RU")
}
