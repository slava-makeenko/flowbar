import Foundation

/// Чтение метаданных играющего трека.
public protocol NowPlayingReading: Sendable {

  /// Что сейчас звучит.
  ///
  /// Возвращает `.silence`, если источник ничего не знает. Реализация **не имеет права**
  /// подставлять заглушку вместо реальных данных: вьюха рассчитывает показать ровно
  /// то, что известно, а не «Неизвестный трек». Контракт — часть протокола, а не деталь
  /// реализации.
  ///
  /// Случай `.application` существует именно для честности: знать, что звук идёт из
  /// Safari, — это меньше, чем знать трек, но больше, чем не знать ничего.
  func current() async -> NowPlaying
}

/// Управление воспроизведением.
///
/// Отдельно от `NowPlayingReading` намеренно: адаптер медиа-клавиш физически не может
/// прочитать метаданные и не должен быть вынужден это притворно уметь.
public protocol PlaybackControlling: Sendable {

  /// Переключает воспроизведение и паузу.
  func toggle() async

  /// Переходит к следующему треку.
  func next() async

  /// Переходит к предыдущему треку.
  func previous() async
}

/// Чтение и изменение позиции внутри трека.
///
/// Отдельный порт: через медиа-клавиши позиция недоступна в принципе, и полосу прогресса
/// в этом случае нужно скрывать, а не показывать нулевой.
public protocol PlaybackSeeking: Sendable {

  /// Текущая позиция воспроизведения.
  /// - Returns: позиция или `nil`, если источник её не отдаёт.
  func position() async -> PlaybackPosition?

  /// Перематывает трек.
  /// - Parameter elapsed: сколько должно быть сыграно после перемотки.
  func seek(to elapsed: TimeInterval) async
}

/// Управление системной громкостью.
///
/// Именно системной, а не громкостью приложения: в макете это общесистемный ползунок.
public protocol SystemVolumeControlling: Sendable {

  /// Текущая громкость от 0 до 1.
  var volume: Double { get async }

  /// Устанавливает громкость.
  /// - Parameter volume: значение от 0 до 1.
  func setVolume(_ volume: Double) async

  /// Имя текущего устройства вывода.
  func outputDeviceName() async -> String?
}
