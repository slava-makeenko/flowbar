import Foundation

/// Источник текущего момента времени.
///
/// Существует ради тестируемости, а не ради педантизма: инварианты со сроком жизни —
/// «чистить копии старше 7 дней» — иначе не проверяются без ожидания в неделю.
public protocol Clock: Sendable {

  /// Текущий момент времени.
  var now: Date { get }
}
